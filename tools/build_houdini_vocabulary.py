# -*- coding: utf-8 -*-
"""Build snippetlib/vocab/houdini_words.txt from the running Houdini: every node
type name and label of every network category, split into words and ranked by
how many node types use them.  Run with hython:

    hython tools/build_houdini_vocabulary.py
"""
import os
import re
import sys

import hou

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from snippetlib.core import split_words  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "snippetlib", "vocab", "houdini_words.txt")
SKIP = {"the", "and", "for", "from", "with", "into", "this", "that", "of", "to", "in", "on", "by", "or", "as", "at",
        "an", "is", "be", "it", "its", "per", "via", "non", "pre", "post", "based", "using", "use", "set", "get",
        "labs", "sidefx", "kinefx", "beta", "test", "example"}
MAX_WORDS = 1500

count = {}
for cat_name, cat in hou.nodeTypeCategories().items():
    for type_name, ntype in cat.nodeTypes().items():
        if ntype.hidden() or ntype.deprecated():
            continue
        # 'labs::foo::2.0' -> 'foo'. Type names are what users type (attribwrangle);
        # labels ("Attribute Wrangle") give the readable words.
        parts = [x for x in type_name.split("::") if x and not re.match(r"^[0-9.]+$", x)]
        base = parts[-1] if parts else type_name
        for src in (base, ntype.description()):
            for w in split_words(src):
                lw = w.lower()
                if len(lw) < 3 or len(lw) > 20 or lw in SKIP or not re.match(r"^[a-z][a-z0-9]*$", lw):
                    continue
                count[lw] = count.get(lw, 0) + 1

# A word used by a single node type is usually a long compound name
# (feathermatchuncondensed); keep words shared by 2+ types, plus short single-use ones.
words = sorted((k for k in count if count[k] >= 2 or len(k) <= 12), key=lambda k: (-count[k], k))
words = words[:MAX_WORDS]
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("# Houdini %s: words from node type names and labels, most common first.\n" % hou.applicationVersionString())
    f.write("# Generated by tools/build_houdini_vocabulary.py - edit by hand if you like.\n")
    for w in words:
        f.write(w + "\n")
print("wrote %s (%d kept of %d)" % (OUT, len(words), len(count)))
print("top:", words[:40])
